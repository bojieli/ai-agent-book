def panel(f, x, y, w, title, lines, h=None):
    h = h or 72 + 32 * len(lines)
    f.box(x, y, w, h, '#ffffff')
    f.box(x, y, w, 48, '#dedede')
    f.text(x+w/2, y+33, title, 23, True)
    for i, line in enumerate(lines):
        f.text(x+w/2, y+80+i*32, line, 20)
    return y+h


def down(f, x, start, end):
    f.path([(x,start),(x,end)],True)


