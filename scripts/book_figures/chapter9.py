def verification():
    f = Figure('从环境结果到 LLM Rubric 的三层轨迹验证',
               '示例：把客服的全额退款承诺与业务状态、授权、时效和答复逐项核对。', 920)
    panel(f, 20, 20, 860, '审读同一次退款',
          ['用户要求全额退款；客服回复“已全额退回，七天内到账”。'], 115)
    for i, (label, record, conclusion) in enumerate([
        ('结果验证器', '订单记录：只退回部分金额', '全额退款尚未完成'),
        ('过程验证器', '动作日志：退款已提交', '还要核对权限和到账时效'),
        ('质量 · LLM Rubric', '答复原文：声称“全额”“七天”', '表达评分不能替代订单核验'),
    ]):
        y = 190+i*150
        panel(f, 20, y, 430, label, [record], 115)
        f.path([(450, y+58), (502, y+58)], True)
        f.box(502, y, 378, 115)
        f.text(691, y+58, conclusion)
    panel(f, 20, 663, 860, '写进轨迹评价，交给后续诊断',
          ['任务结果：部分完成；问题标签：承诺与实际金额不符',
           '证据位置：对应的订单、操作记录和客服原话',
           '待核实：七天到账的依据；保留记录供独立检查'], 198)
    f.save('fig9-2.svg')


